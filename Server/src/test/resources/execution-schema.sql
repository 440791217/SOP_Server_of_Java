CREATE TABLE IF NOT EXISTS sop_execution (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 request_key VARCHAR(64) NOT NULL,
 task_id BIGINT NOT NULL, project_id BIGINT NOT NULL, subproject_id BIGINT NOT NULL,
 station_id BIGINT NOT NULL, active_station_id BIGINT NULL,
 sop_id BIGINT NOT NULL, revision_id BIGINT NOT NULL,
 operator_id BIGINT NOT NULL,
 product_code VARCHAR(128) NOT NULL,
 task_name VARCHAR(128) NOT NULL, project_name VARCHAR(128) NOT NULL,
 subproject_name VARCHAR(128) NOT NULL, station_name VARCHAR(255) NOT NULL,
 operator_name VARCHAR(128) NOT NULL, revision_no INT NOT NULL,
 content_snapshot CLOB NOT NULL,
 status TINYINT NOT NULL DEFAULT 0,
 version INT NOT NULL DEFAULT 0,
 started_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 ended_at DATETIME(3) NULL, updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 CONSTRAINT uk_execution_request UNIQUE(operator_id,request_key),
 CONSTRAINT uk_execution_product UNIQUE(task_id,product_code),
 CONSTRAINT uk_execution_station UNIQUE(active_station_id),
 CONSTRAINT ck_execution_status CHECK(status IN(0,1,2,3)),
 CONSTRAINT ck_execution_active CHECK((status IN(0,1) AND active_station_id IS NOT NULL AND active_station_id=station_id) OR (status IN(2,3) AND active_station_id IS NULL)),
 FOREIGN KEY(task_id) REFERENCES sop_task(id), FOREIGN KEY(project_id) REFERENCES sop_project(id),
 FOREIGN KEY(subproject_id) REFERENCES sop_subproject(id), FOREIGN KEY(station_id) REFERENCES sop_station(id),
 FOREIGN KEY(operator_id) REFERENCES sys_user(id), FOREIGN KEY(sop_id,revision_id) REFERENCES sop_revision(sop_id,id),
 INDEX ix_execution_started(started_at,id), INDEX ix_execution_station(station_id,status)
);
CREATE TABLE IF NOT EXISTS sop_execution_step (
 execution_id BIGINT NOT NULL, position INT NOT NULL, step_id BIGINT NOT NULL,
 confirmed_at DATETIME(3) NULL, confirmed_by BIGINT NULL,
 PRIMARY KEY(execution_id,position), UNIQUE(execution_id,step_id),
 FOREIGN KEY(execution_id) REFERENCES sop_execution(id), FOREIGN KEY(confirmed_by) REFERENCES sys_user(id)
);
CREATE TABLE IF NOT EXISTS sop_execution_event (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, execution_id BIGINT NOT NULL,
 action VARCHAR(16) NOT NULL, reason VARCHAR(2000) NULL, actor_id BIGINT NOT NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 FOREIGN KEY(execution_id) REFERENCES sop_execution(id), FOREIGN KEY(actor_id) REFERENCES sys_user(id),
 INDEX ix_execution_event(execution_id,id)
);
