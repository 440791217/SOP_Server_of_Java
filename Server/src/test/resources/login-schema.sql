CREATE TABLE sys_team (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(64) NOT NULL UNIQUE, status TINYINT DEFAULT 1 NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE sys_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    username VARCHAR(64) NOT NULL UNIQUE,
    password_hash VARCHAR(255), real_name VARCHAR(64) NOT NULL,
    card_number VARCHAR(64), team_id BIGINT, phone VARCHAR(20), avatar_url VARCHAR(255),
    status TINYINT DEFAULT 1 NOT NULL, is_superuser TINYINT DEFAULT 0 NOT NULL,
    must_change_password TINYINT DEFAULT 1 NOT NULL,
    password_changed_at TIMESTAMP, last_login_at TIMESTAMP, deleted_at TIMESTAMP,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    version INT DEFAULT 0 NOT NULL,
    active_card_number VARCHAR(64) GENERATED ALWAYS AS (CASE WHEN deleted_at IS NULL THEN card_number ELSE NULL END),
    UNIQUE(active_card_number), FOREIGN KEY(team_id) REFERENCES sys_team(id),
    CHECK(status IN(0,1,2))
);
CREATE TABLE sys_user_session (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES sys_user(id), token_hash BINARY(32) UNIQUE NOT NULL,
    created_at TIMESTAMP NOT NULL, expires_at TIMESTAMP NOT NULL, revoked_at TIMESTAMP,
    CHECK (expires_at > created_at)
);
CREATE TABLE sys_role (id BIGINT PRIMARY KEY, code VARCHAR(64) UNIQUE, status TINYINT, name VARCHAR(64));
CREATE TABLE sys_permission (id BIGINT PRIMARY KEY, code VARCHAR(100) UNIQUE);
CREATE TABLE sys_user_role (
    user_id BIGINT REFERENCES sys_user(id), role_id BIGINT REFERENCES sys_role(id),
    PRIMARY KEY(user_id, role_id)
);
CREATE TABLE sys_role_permission (
    role_id BIGINT REFERENCES sys_role(id), permission_id BIGINT REFERENCES sys_permission(id),
    PRIMARY KEY(role_id, permission_id)
);
